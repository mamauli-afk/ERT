/* SP_CLIENT_CARD */
CREATE OR ALTER PROCEDURE SP_CLIENT_CARD (
    CLIENT_ID_PARAM INTEGER
) 
RETURNS (
    FULL_NAME VARCHAR(250),
    CITY_NAME VARCHAR(100),
    GROUP_NAME VARCHAR(100),
    PHONE_COUNT INTEGER
)
AS
BEGIN
    SELECT
        TRIM(c.LAST_NAME) || ' ' || TRIM(c.FIRST_NAME) ||
            COALESCE(' ' || TRIM(c.MIDDLE_NAME), ''),
        ci.NAME,
        cg.NAME,
        (SELECT COUNT(*) FROM PHONE p WHERE p.CLIENT_ID = c.ID)
    FROM CLIENT c
    LEFT JOIN CITY ci          ON ci.ID = c.CITY_ID
    LEFT JOIN CONTACT_GROUP cg ON cg.ID = c.GROUP_ID
    WHERE c.ID = :CLIENT_ID_PARAM
    INTO :FULL_NAME, :CITY_NAME, :GROUP_NAME, :PHONE_COUNT;
    SUSPEND;
END;

