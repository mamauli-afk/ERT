/* V_CLIENT_PHONES */
CREATE OR ALTER VIEW V_CLIENT_PHONES (CLIENT_ID, LAST_NAME, FIRST_NAME, PHONE_NUMBER, PHONE_TYPE, IS_PRIMARY) 
AS 
SELECT
    c.ID AS CLIENT_ID,
    c.LAST_NAME,
    c.FIRST_NAME,
    p.NUMBER AS PHONE_NUMBER,
    pt.NAME  AS PHONE_TYPE,
    p.IS_PRIMARY
FROM CLIENT c
JOIN PHONE p       ON p.CLIENT_ID = c.ID
JOIN PHONE_TYPE pt ON pt.ID = p.PHONE_TYPE_ID
;

/* V_CLIENT_FULL */
CREATE OR ALTER VIEW V_CLIENT_FULL (ID, LAST_NAME, FIRST_NAME, MIDDLE_NAME, EMAIL, BIRTH_DATE, CITY_NAME, GROUP_NAME, CREATED_AT) 
AS 
SELECT
    c.ID,
    c.LAST_NAME,
    c.FIRST_NAME,
    c.MIDDLE_NAME,
    c.EMAIL,
    c.BIRTH_DATE,
    ci.NAME AS CITY_NAME,
    cg.NAME AS GROUP_NAME,
    c.CREATED_AT
FROM CLIENT c
LEFT JOIN CITY ci          ON ci.ID = c.CITY_ID
LEFT JOIN CONTACT_GROUP cg ON cg.ID = c.GROUP_ID
;

/* V_CITY_STATS */
CREATE OR ALTER VIEW V_CITY_STATS (CITY_ID, CITY_NAME, CLIENT_COUNT) 
AS 
SELECT
    ci.ID       AS CITY_ID,
    ci.NAME     AS CITY_NAME,
    COUNT(c.ID) AS CLIENT_COUNT
FROM CITY ci
LEFT JOIN CLIENT c ON c.CITY_ID = ci.ID
GROUP BY ci.ID, ci.NAME
;

