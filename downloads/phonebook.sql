/* SP_GET_PHONE_INFO */
CREATE OR ALTER PROCEDURE SP_GET_PHONE_INFO (
    PHONE_ID_PARAM INTEGER
) 
RETURNS (
    PHONE_NUMBER VARCHAR(20),
    CLIENT_NAME VARCHAR(250),
    PHONE_TYPE_NAME VARCHAR(100)
)
AS
DECLARE CNT INTEGER;
BEGIN
    SELECT COUNT(*) FROM PHONE WHERE ID = :PHONE_ID_PARAM INTO :CNT;
    IF (CNT = 0) THEN
        EXCEPTION E_PHONE_NOT_FOUND;

    SELECT
        ph.NUMBER,
        TRIM(c.LAST_NAME) || ' ' || TRIM(c.FIRST_NAME),
        pt.NAME
    FROM PHONE ph
    JOIN CLIENT c       ON c.ID = ph.CLIENT_ID
    JOIN PHONE_TYPE pt  ON pt.ID = ph.PHONE_TYPE_ID
    WHERE ph.ID = :PHONE_ID_PARAM
    INTO :PHONE_NUMBER, :CLIENT_NAME, :PHONE_TYPE_NAME;
    SUSPEND;
END;

